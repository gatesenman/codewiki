#!/usr/bin/env node
/**
 * Render a CodeWiki impact report (the JSON emitted by
 * `codewiki git-diff . --base <ref> --json`) into a Markdown PR comment.
 *
 * Usage:
 *   codewiki git-diff . --base origin/main --json | node scripts/pr-impact-comment.mjs
 *
 * Reads the JSON on stdin, prints Markdown on stdout. Pure formatting, no IO
 * beyond stdin/stdout so it is trivially testable.
 */

const RISK_EMOJI = { critical: '🔴', high: '🟠', medium: '🟡', low: '🟢' }
export const MARKER = '<!-- codewiki-impact-bot -->'

export function renderComment(report) {
  if (!report || report.error) {
    return `${MARKER}\n### CodeWiki Impact Analysis\n\n_Could not compute impact: ${report?.error ?? 'unknown error'}._`
  }

  const changed = report.changedFiles ?? []
  const symbols = report.affectedSymbols ?? []
  const sum = report.riskSummary ?? { low: 0, medium: 0, high: 0, critical: 0 }
  const overall = report.overallRisk ?? 'low'

  const lines = []
  lines.push(MARKER)
  lines.push(`### ${RISK_EMOJI[overall] ?? ''} CodeWiki Impact Analysis — overall risk: **${overall.toUpperCase()}**`)
  lines.push('')

  if (changed.length === 0) {
    lines.push('_No code files changed in this PR._')
    return lines.join('\n')
  }

  lines.push(`**${changed.length}** changed file(s), **${symbols.length}** affected symbol(s).`)
  lines.push('')
  lines.push(
    `Risk: ${RISK_EMOJI.critical} ${sum.critical} critical · ` +
    `${RISK_EMOJI.high} ${sum.high} high · ` +
    `${RISK_EMOJI.medium} ${sum.medium} medium · ` +
    `${RISK_EMOJI.low} ${sum.low} low`,
  )
  lines.push('')

  // Highlight the riskiest symbols (those with dependents).
  const risky = symbols.filter(s => s.dependentCount > 0).slice(0, 15)
  if (risky.length) {
    lines.push('| Risk | Symbol | Type | Dependents | File |')
    lines.push('| --- | --- | --- | --: | --- |')
    for (const s of risky) {
      const file = String(s.file).split(/[/\\]/).slice(-2).join('/')
      lines.push(`| ${RISK_EMOJI[s.risk] ?? ''} ${s.risk} | \`${s.name}\` | ${s.type} | ${s.dependentCount} | \`${file}\` |`)
    }
    lines.push('')
    const topTests = risky.filter(s => s.risk === 'high' || s.risk === 'critical')
    if (topTests.length) {
      lines.push('> ⚠️ High-impact changes detected. Consider running the test suites that exercise the symbols above before merging.')
    }
  } else {
    lines.push('_No downstream dependents found for the changed symbols — low blast radius._')
  }

  lines.push('')
  lines.push('<sub>Generated by CodeWiki — ontology-based impact analysis.</sub>')
  return lines.join('\n')
}

async function readStdin() {
  const chunks = []
  for await (const c of process.stdin) chunks.push(c)
  return Buffer.concat(chunks).toString('utf-8')
}

// Run only when invoked directly (not when imported by tests).
const invokedDirectly = process.argv[1] && import.meta.url === `file://${process.argv[1]}`
if (invokedDirectly) {
  const raw = await readStdin()
  let report
  try {
    report = JSON.parse(raw)
  } catch {
    report = { error: 'invalid JSON from codewiki CLI' }
  }
  process.stdout.write(renderComment(report) + '\n')
}
