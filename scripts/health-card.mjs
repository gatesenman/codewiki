#!/usr/bin/env node
/**
 * Render a CodeWiki health card from the JSON emitted by
 * `codewiki report json` and inject it into README files between markers.
 *
 * Usage:
 *   codewiki report json --project . -o report.json
 *   node scripts/health-card.mjs report.json README.md README.zh-CN.md
 *
 * If no README files are given, the rendered card is printed to stdout (pure,
 * testable). When README paths are given, the block between the markers
 * <!-- codewiki-health-card:start --> and <!-- codewiki-health-card:end -->
 * is replaced in-place (files without the markers are skipped).
 */

import { readFileSync, writeFileSync, existsSync } from 'fs'

export const START = '<!-- codewiki-health-card:start -->'
export const END = '<!-- codewiki-health-card:end -->'

const GRADE_COLOR = { A: 'brightgreen', B: 'green', C: 'yellow', D: 'orange', F: 'red' }

function badge(label, message, color) {
  const enc = (s) => encodeURIComponent(String(s)).replace(/-/g, '--').replace(/_/g, '__')
  return `https://img.shields.io/badge/${enc(label)}-${enc(message)}-${color}`
}

export function renderCard(report, eol = '\n') {
  const h = report?.health ?? {}
  const sec = report?.security ?? {}
  const pat = report?.patterns ?? {}
  const grade = h.grade ?? '?'
  const score = h.score ?? 0
  const m = h.metrics ?? {}
  const sev = sec.bySeverity ?? { high: 0, medium: 0, low: 0 }

  const lines = []
  lines.push(START)
  lines.push('')
  lines.push('### Code Health')
  lines.push('')
  lines.push(
    `![Health](${badge('health', `${grade} (${score}/100)`, GRADE_COLOR[grade] ?? 'lightgrey')}) ` +
    `![Circular deps](${badge('circular deps', m.circularDependencies ?? 0, (m.circularDependencies ?? 0) > 0 ? 'orange' : 'brightgreen')}) ` +
    `![Dead code](${badge('dead code', m.deadCode ?? 0, 'informational')}) ` +
    `![God objects](${badge('god objects', m.godObjects ?? 0, (m.godObjects ?? 0) > 0 ? 'orange' : 'brightgreen')}) ` +
    `![Security](${badge('security', `${sev.high}H ${sev.medium}M ${sev.low}L`, sev.high > 0 ? 'red' : sev.medium > 0 ? 'orange' : 'brightgreen')})`,
  )
  lines.push('')
  lines.push(`> ${m.entityCount ?? 0} entities · ${m.relationCount ?? 0} relations · ${m.fileCount ?? 0} files · avg degree ${m.avgDegree ?? 0} · ${pat.total ?? 0} pattern-tagged entities`)
  lines.push('')
  lines.push(`<sub>Generated by \`codewiki report\` on ${report?.generated ?? new Date().toISOString()}.</sub>`)
  lines.push('')
  lines.push(END)
  return lines.join(eol)
}

export function injectCard(content, card) {
  const s = content.indexOf(START)
  const e = content.indexOf(END)
  if (s === -1 || e === -1 || e < s) return null
  return content.slice(0, s) + card + content.slice(e + END.length)
}

function main() {
  const [jsonPath, ...readmes] = process.argv.slice(2)
  if (!jsonPath) {
    console.error('Usage: node scripts/health-card.mjs <report.json> [README.md ...]')
    process.exit(1)
  }
  const report = JSON.parse(readFileSync(jsonPath, 'utf8'))
  if (readmes.length === 0) {
    process.stdout.write(renderCard(report) + '\n')
    return
  }
  let changed = 0
  for (const file of readmes) {
    if (!existsSync(file)) continue
    const content = readFileSync(file, 'utf8')
    const eol = content.includes('\r\n') ? '\r\n' : '\n'
    const card = renderCard(report, eol)
    const updated = injectCard(content, card)
    if (updated && updated !== content) {
      writeFileSync(file, updated, 'utf8')
      changed++
      console.log(`Updated health card in ${file}`)
    } else if (!updated) {
      console.log(`No markers found in ${file} (skipped)`)
    } else {
      console.log(`${file} already up to date`)
    }
  }
  console.log(`changed=${changed}`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
